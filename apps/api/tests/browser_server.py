"""API bootstrap for disposable browser tests; never use for an owner app.

Browser routes mock lookup/preview. The final save fetches artwork in the API,
so provide generated bytes at that external boundary while retaining the real
media validation, transactions, provenance and download routes.
"""
import os

if os.environ.get("RELICRAT_SYNTHETIC_SMOKE") != "1":
    raise SystemExit("Refusing synthetic provider outside an explicit test API")

from sqlalchemy.engine import make_url

if not (make_url(os.environ["DATABASE_URL"]).database or "").endswith("_test"):
    raise SystemExit("Synthetic browser API requires a disposable _test database")

import io

from PIL import Image
import uvicorn
from relicrat.barcode_errors import LookupUnavailable
from relicrat.barcode_providers import PROVIDERS


def cover(candidate_id):
    if candidate_id != "11111111-1111-4111-8111-111111111111":
        raise LookupUnavailable()
    output = io.BytesIO()
    Image.new("RGB", (8, 8), "purple").save(output, format="JPEG")
    return output.getvalue()


PROVIDERS["musicbrainz"]["cover"] = cover
uvicorn.run("relicrat.main:app", host="0.0.0.0", port=8000)
